import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {rank,distance} from '../prototypes/search.js';
import {makeTree,findNode,immediateNotes} from '../prototypes/navigation.js';
import {latestPublished,latestAtlasPublished} from '../prototypes/publication.js';
import {readerMetas,readerAliases} from '../prototypes/readers/index.js';
import {reviewedNavigation} from '../prototypes/reviewed-navigation.js';
import {isRetiredNote} from '../prototypes/retired-navigation.js';
import './test-file-explorer.mjs';
import './test-reader-links.mjs';
import './test-math.mjs';
import './test-navigation-integrity.mjs';
import './test-site-shell.mjs';
import './test-reader-history.mjs';

const catalog=JSON.parse(await readFile(new URL('../prototypes/catalog.json',import.meta.url),'utf8'));
const sources=catalog.notes.filter(n=>n.tracked&&!n.navigationPage&&!n.draft&&!n.unlisted&&!isRetiredNote(n.slug));
const canonical=[...readerMetas,...sources.filter(n=>!readerAliases.includes(n.slug)&&!reviewedNavigation[n.slug])];
assert.equal(canonical.length,54,'The browsable atlas must contain only canonical readers');
assert(canonical.every(n=>!isRetiredNote(n.slug)));
assert.equal(rank(canonical,'two sum').filter(r=>r.note.slug.includes('leetcode/')).length,0);
const canonicalLatest=latestAtlasPublished(canonical);
assert.equal(canonicalLatest.length,3,'Canonical migration must not empty the homepage carousel');
assert(canonicalLatest.every(n=>readerMetas.some(meta=>meta.slug===n.slug&&meta.date===n.date)));
assert.deepEqual(latestAtlasPublished(canonical.map(n=>({...n,updated:'2099-01-01'}))).map(n=>n.slug),canonicalLatest.map(n=>n.slug));
assert(catalog.notes.every(n=>n.tracked&&!n.navigationPage&&!n.draft&&!n.unlisted),'Private/local/navigation entries must not be shipped in the public catalog');
const notes=catalog.notes.filter(n=>!n.draft&&!n.unlisted&&n.tracked&&!n.navigationPage);
const guide={slug:'ai/architectures/moe',prototype:true,title:'Mixture of Experts',description:'A main explainer of sparse routing.',tags:['moe','mixture of experts']};
notes.push(guide);
const root=makeTree(notes);
assert.equal(root.notes.length,notes.length);
assert.equal(immediateNotes(root,[]).length,0);
assert.equal(immediateNotes(root,['ai']).length,0);
assert.equal(immediateNotes(root,['ai','architectures','moe']).length,4);
const branch=['ai','architectures'];
assert(immediateNotes(root,branch).every(n=>n.browsePath.length===branch.length));
assert(immediateNotes(root,branch).length<findNode(root,branch).notes.length);
assert.equal(distance('exparts','experts'),1);
for(const query of ['mixture of exparts','mixtuer of experts','MoE']) assert.equal(rank(notes,query)[0].note,guide,query);
assert(rank(notes,'speculativ decoding').some(r=>r.note.title==='Speculative Decoding'));
assert(rank(notes,'dfs').some(r=>r.note.slug==='interview-prep/neetcode-roadmap/trees'));
assert.equal(rank(notes,'zzzzzzzznotaword').length,0);
assert(findNode(root,['ai','architectures','moe']).notes.some(n=>n.slug.endsWith('moe-routing-and-load-balancing')));
assert(findNode(root,['algorithms','structures','trees']).notes.some(n=>n.tags.includes('neetcode')));
assert(!root.children.has('interview-prep'));
assert.equal(new Set(root.notes.map(n=>n.slug)).size,notes.length);
console.log('Search aliases, typo ranking, unique entries, MoE hierarchy, and subject/collection separation pass.');

const recent=latestPublished(notes);
assert.equal(recent.length,3);
assert(recent.every(n=>n.tracked&&!n.prototype&&!n.draft&&!n.unlisted));
const fixture=(slug,date,extra={})=>({slug,title:slug,date,tracked:true,...extra});
const published=[fixture('older','2026-09-01',{updated:'2099-01-01'}),fixture('newest','2026-10-02'),fixture('middle','2026-10-01'),fixture('draft','2026-12-01',{draft:true}),fixture('hidden','2026-12-02',{unlisted:true}),fixture('local','2026-12-03',{tracked:false}),fixture('prototype','2026-12-04',{prototype:true}),fixture('missing',null)];
assert.deepEqual(latestPublished(published).map(n=>n.slug),['newest','middle','older']);
assert.deepEqual(latestPublished([]),[]);
assert.equal(latestPublished(published,1).length,1);
console.log('Latest published notes exclude drafts/local/prototype entries and ignore update dates.');
